const languageButtons = document.querySelectorAll('[data-lang-toggle]');
const themeButtons = document.querySelectorAll('[data-theme-toggle]');
const translatedNodes = document.querySelectorAll('[data-i18n]');

function setLanguage(lang) {
  const map = translations[lang] || translations.ur;
  translatedNodes.forEach((node) => {
    const key = node.getAttribute('data-i18n');
    if (map[key]) {
      node.textContent = map[key];
    }
  });

  document.body.setAttribute('data-lang', lang);
  document.body.setAttribute('lang', lang);

  languageButtons.forEach((button) => {
    const isActive = button.getAttribute('data-lang-toggle') === lang;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
}

function setTheme(theme) {
  const isLight = theme === 'light';
  document.body.classList.toggle('theme-light', isLight);
  document.body.classList.toggle('theme-dark', !isLight);

  themeButtons.forEach((button) => {
    const isActive = button.getAttribute('data-theme-toggle') === theme;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
}

languageButtons.forEach((button) => {
  button.addEventListener('click', () => {
    setLanguage(button.getAttribute('data-lang-toggle'));
  });
});

themeButtons.forEach((button) => {
  button.addEventListener('click', () => {
    setTheme(button.getAttribute('data-theme-toggle'));
  });
});

setTheme('dark');
setLanguage('ur');
